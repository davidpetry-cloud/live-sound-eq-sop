#!/usr/bin/env node
/**
 * Reference values for the Dart filter maths, taken from the page's own JS.
 *
 * The biquads in public/app.js (biquad, magDb, filtersFor, responseOf) are
 * lifted out of the file as text and run here, so the reference is the code
 * the channel cards actually draw with, not a copy of it. The Dart test
 * (strip/test/eq_test.dart) must match these within 0.01 dB, and
 * tests/strip-reference.test.js fails if app.js drifts from the saved file.
 *
 *   node strip/tool/js_reference.mjs           write strip/test/js_reference.json
 *   node strip/tool/js_reference.mjs --print   print it instead
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { GROUPS, toHz, CONSOLE } from "../../src/data.js";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
export const OUT = join(ROOT, "strip", "test", "js_reference.json");

/** The curve maths from app.js, from its constants through responseOf(). */
export function appMaths(source = readFileSync(join(ROOT, "public", "app.js"), "utf8")) {
  const start = source.indexOf("const FS = 96000");
  const end = source.indexOf("function pathOf");
  if (start < 0 || end < start) throw new Error("app.js: could not find the EQ curve maths");
  const body = source.slice(start, end);
  return new Function("toHz", "CONSOLE", `${body}\nreturn { FS, biquad, magDb, responseOf };`)(toHz, CONSOLE);
}

/** 64 log-spaced frequencies, 20 Hz to 20 kHz. */
export const FREQS = Array.from({ length: 64 }, (_, i) => 20 * 1000 ** (i / 63));

/* A gain is a number, or a range written as text; the cards draw both ends. */
const ends = (v) => typeof v === "number" ? [v, v]
  : (String(v).match(/[−+-]?\d+(\.\d+)?/g) || ["0"]).map((x) => parseFloat(x.replace("−", "-")));
const at = (b, i) => ({ ...b, lf: ends(b.lf)[i], lmD: ends(b.lmD)[i], hmD: ends(b.hmD)[i], hf: ends(b.hf)[i] });

/** Settings at the console's limits and in between, in the records' own format. */
function edgeCases() {
  const hz = (f) => f >= 1000 ? `${f / 1000} kHz` : `${f} Hz`;
  const cases = [
    { hpf: "IN", lf: 15, lmF: hz(35), lmD: 15, hmF: hz(500), hmD: 15, hf: 15 },
    { hpf: "IN", lf: -15, lmF: hz(1000), lmD: -15, hmF: hz(15000), hmD: -15, hf: -15 },
    { hpf: "OUT", lf: 0, lmF: "0 dB", lmD: 0, hmF: "0 dB", hmD: 0, hf: 0 },
    { hpf: "IN", lf: 0, lmF: "0 dB", lmD: 0, hmF: "0 dB", hmD: 0, hf: 0 },
    { hpf: "OUT", lf: 0, lmF: hz(500), lmD: 9, hmF: hz(500), hmD: -9, hf: 0 },
  ];
  // A fixed sequence, so the file only changes when the maths do.
  let seed = 7;
  const rnd = () => (seed = (seed * 16807) % 2147483647) / 2147483647;
  const pick = (lo, hi) => Math.round(lo * (hi / lo) ** rnd());
  const gain = () => Math.round(rnd() * 30 - 15);
  for (let i = 0; i < 24; i++) {
    cases.push({
      hpf: rnd() < 0.5 ? "IN" : "OUT", lf: gain(),
      lmF: hz(pick(35, 1000)), lmD: gain(), hmF: hz(pick(500, 15000)), hmD: gain(), hf: gain()
    });
  }
  return cases;
}

export function buildReference(maths = appMaths()) {
  const cases = [];
  const add = (label, bands) => {
    const resp = maths.responseOf(bands);
    cases.push({ label, bands, db: FREQS.map((f) => Number(resp(f).toFixed(6))) });
  };
  for (const group of GROUPS) {
    for (const ch of group.channels) {
      const id = ch.variant ? `${ch.name} (${ch.variant})` : ch.name;
      add(id, at(ch.bands, 0));
      const hi = at(ch.bands, 1);
      if (JSON.stringify(hi) !== JSON.stringify(at(ch.bands, 0))) add(`${id}, high end`, hi);
    }
  }
  edgeCases().forEach((b, i) => add(`limits ${i + 1}`, b));
  return {
    about: "Generated by strip/tool/js_reference.mjs from public/app.js. dB at each frequency in freqs.",
    sampleRate: maths.FS,
    freqs: FREQS.map((f) => Number(f.toFixed(6))),
    cases
  };
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const text = JSON.stringify(buildReference(), null, 1) + "\n";
  if (process.argv.includes("--print")) process.stdout.write(text);
  else { writeFileSync(OUT, text); console.log(`Wrote ${OUT}`); }
}
